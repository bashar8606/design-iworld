// assets:optimize — compresses every .glb in assets-src/export into public/models and generates a
// typed React Three Fiber component for each one in src/scene/models/generated.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../..')
const srcDir = join(root, 'assets-src/export')
const outDir = join(root, 'public/models')
const genDir = join(root, 'src/scene/models/generated')
const bin = (name: string) => join(root, 'node_modules/.bin', name)

const only = process.argv.slice(2).filter((a) => !a.startsWith('-'))

export function componentName(file: string): string {
  return basename(file, '.glb')
    .split(/[-_ ]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('')
}

/** Makes gltfjsx output compile under React 19, strict TypeScript and any base URL. */
export function patchComponent(source: string, file: string, name: string): string {
  const url = `\`\${import.meta.env.BASE_URL}models/${file}\``
  let out = source
    .replace(/^\/\*[\s\S]*?\*\/\s*/m, '')
    .replace(/^\/\*[\s\S]*?\*\/\s*/m, '')
    .replace(
      "import { GLTF, SkeletonUtils } from 'three-stdlib'",
      "import { SkeletonUtils } from 'three-stdlib'\nimport type { GLTF } from 'three-stdlib'",
    )
    .replace("import { GLTF } from 'three-stdlib'", "import type { GLTF } from 'three-stdlib'")
    .replace(/JSX\.IntrinsicElements\['group'\]/g, "ThreeElements['group']")
    .replace(/React\.useRef<THREE\.Group>\(\)/g, 'React.useRef<THREE.Group>(null)')
    .replace(/useGLTF\('[^']*'\)/g, `useGLTF(${url})`)
    .replace(/useGLTF\.preload\('[^']*'\)/g, `useGLTF.preload(${url})`)
    .replace('export function Model(', `export function ${name}(`)
  out = out.replace(/\) as GLTFResult/g, ') as unknown as GLTFResult')
  if (!out.includes('interface GLTFAction')) {
    out = out.replace('animations: GLTFAction[]', 'animations: THREE.AnimationClip[]')
  }
  if (!/React\./.test(out.replace("import React from 'react'", ''))) {
    out = out.replace("import React from 'react'\n", '')
  }
  // Animated models take an `animation` prop that cross-fades between clips.
  if (out.includes('const { actions } = useAnimations(animations, group)')) {
    out = out
      .replace(
        `export function ${name}(props: ThreeElements['group']) {`,
        `export function ${name}({ animation, ...props }: ThreeElements['group'] & { animation?: ActionName }) {`,
      )
      .replace(
        'const { actions } = useAnimations(animations, group)',
        `const { actions } = useAnimations(animations, group)
  React.useEffect(() => {
    if (!animation) return
    const action = actions[animation]
    action?.reset().fadeIn(0.2).play()
    return () => {
      action?.fadeOut(0.2)
    }
  }, [animation, actions])`,
      )
  }
  const fiberImport = out.match(/import \{([^}]*)\} from '@react-three\/fiber'/)
  if (fiberImport) {
    out = out.replace(
      fiberImport[0],
      `import {${fiberImport[1]}, type ThreeElements } from '@react-three/fiber'`,
    )
  } else {
    out = out.replace(
      "import * as THREE from 'three'",
      "import * as THREE from 'three'\nimport type { ThreeElements } from '@react-three/fiber'",
    )
  }
  // Types are loose in gltfjsx output; keep the generated file as-is otherwise.
  return `// Generated by tools/assets/optimize.ts from assets-src/export/${file}. Do not edit.\n${out}`
}

function main() {
  mkdirSync(outDir, { recursive: true })
  mkdirSync(genDir, { recursive: true })
  const files = readdirSync(srcDir)
    .filter((f) => f.endsWith('.glb'))
    .filter((f) => only.length === 0 || only.includes(basename(f, '.glb')))
  if (files.length === 0) throw new Error(`No .glb files in ${srcDir}`)

  for (const file of files) {
    const out = join(outDir, file)
    execFileSync(
      bin('gltf-transform'),
      [
        'optimize',
        join(srcDir, file),
        out,
        '--compress',
        'meshopt',
        '--texture-compress',
        'webp',
        '--texture-size',
        '1024',
        '--simplify',
        'false',
        '--palette',
        'false',
      ],
      { stdio: 'pipe' },
    )
    const name = componentName(file)
    const tsx = join(genDir, `${name}.tsx`)
    execFileSync(bin('gltfjsx'), [`models/${file}`, '--types', '--output', tsx, '--root', '/'], {
      cwd: join(root, 'public'),
      stdio: 'pipe',
    })
    writeFileSync(tsx, patchComponent(readFileSync(tsx, 'utf8'), file, name))
    const before = readFileSync(join(srcDir, file)).length
    const after = readFileSync(out).length
    console.log(
      `${file}: ${(before / 1024).toFixed(0)} KB → ${(after / 1024).toFixed(0)} KB, ${name}.tsx`,
    )
  }
  if (!existsSync(join(genDir, 'index.ts')) || only.length === 0) {
    const names = readdirSync(genDir)
      .filter((f) => f.endsWith('.tsx'))
      .map((f) => basename(f, '.tsx'))
      .sort()
    writeFileSync(
      join(genDir, 'index.ts'),
      `// Generated by tools/assets/optimize.ts. Do not edit.\n${names.map((n) => `export { ${n} } from './${n}.tsx'`).join('\n')}\n`,
    )
  }
  execFileSync(bin('prettier'), ['--write', genDir], { stdio: 'pipe' })
}

if (import.meta.url === `file://${process.argv[1]}`) main()
